"""Passive, bounded direct-Ethernet printer endpoint discovery.

Linux neighbor entries are learned by the OS, not generated by a scan here.
Only use a dedicated Pi Ethernet interface with no default route. This module
never sends packets, discovers WAN hosts or proves the peer is a printer.
The Hitachi read-only identity probe must verify the candidate separately.
"""
from __future__ import annotations

import ipaddress
import json
import re
import subprocess

from .printer_detection import PrinterTarget

INTERFACE_RE = re.compile(r"^[a-zA-Z0-9_.-]{1,15}$")
VALID_STATES = {"REACHABLE", "STALE", "DELAY", "PROBE", "PERMANENT"}


def linux_json(*args: str, runner=subprocess.run) -> list[dict]:
    completed = runner(
        ["ip", "-j", *args], capture_output=True, text=True,
        check=True, timeout=5,
    )
    data = json.loads(completed.stdout)
    if not isinstance(data, list):
        raise ValueError("Unexpected Linux network information")
    return data


def passive_direct_link_target(
    *, interface: str = "eth0", port: int = 502,
    network_info=linux_json,
) -> PrinterTarget | None:
    """Return exactly one learned peer from isolated wired Ethernet.

    No default route can use this interface. Zero peers returns None; more
    than one fails closed. The actual Modbus model/serial probe is still needed.
    """
    if not INTERFACE_RE.fullmatch(interface) or interface.startswith("-"):
        raise ValueError("Invalid Ethernet interface")
    if type(port) is not int or not 1 <= port <= 65535:
        raise ValueError("Invalid Modbus TCP port")
    # Refuse discovery on an uplink or shared LAN with the Pi's default route.
    if network_info("route", "show", "default", "dev", interface):
        raise ValueError("Ethernet interface is used as a default route; not a dedicated printer link")
    entries = network_info("neigh", "show", "dev", interface)
    candidates = set()
    for entry in entries:
        if entry.get("dev") != interface:
            continue
        state = entry.get("state", "")
        if isinstance(state, list):
            state = state[0] if len(state) == 1 else ""
        if state.upper() not in VALID_STATES:
            continue
        try:
            address = ipaddress.ip_address(entry["dst"])
        except (KeyError, ValueError, TypeError):
            continue
        if address.version != 4 or not (address.is_private or address.is_link_local):
            continue
        candidates.add(str(address))
    if len(candidates) > 1:
        raise ValueError("Ambiguous direct link: multiple peers discovered")
    if not candidates:
        return None
    return PrinterTarget(
        host=candidates.pop(), port=port,
        protocol="modbus", manufacturer="Hitachi",
    )
